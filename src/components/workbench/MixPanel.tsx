"use client";

import { useEffect, useRef, useState } from "react";
import Link from "next/link";
import {
  AlertCircle,
  ArrowUpRight,
  Check,
  ChevronDown,
  Copy,
  Loader2,
  RefreshCw,
  Sparkles,
  X,
  Zap,
} from "lucide-react";
import { useWorkbench } from "@/hooks";
import { Button } from "@/components/ui/Button";
import { WorkbenchItem } from "@/types";
import { GUIDE_SECTIONS } from "@/lib/guide-sections";
import { cn } from "@/lib/utils/cn";

interface MixPanelProps {
  workbenchId: string;
  onClose: () => void;
}

/* The generate-in-place rail: opens next to the bookmark grid right after a
   mix is composed, scans its sources, writes the guide, and hands it over —
   no navigation. The full /mix/[id] page stays the deep view. */
export function MixPanel({ workbenchId, onClose }: MixPanelProps) {
  const {
    workbench,
    loading,
    patchWorkbench,
    scanItem,
    generate,
  } = useWorkbench(workbenchId);

  const [genError, setGenError] = useState<string | null>(null);
  const [overLimit, setOverLimit] = useState(false);
  const [copied, setCopied] = useState(false);
  const [notesOpen, setNotesOpen] = useState(false);
  // The guide as it streams in, before it's saved and handed back on workbench.
  const [partial, setPartial] = useState("");
  const autoScanned = useRef<Set<string>>(new Set());
  const autoGenerated = useRef(false);

  const items = workbench?.items ?? [];
  const statusOf = (i: WorkbenchItem) =>
    i.analysis?.analysis_status ?? "pending";
  const completed = items.filter((i) => statusOf(i) === "completed");
  const allResolved =
    items.length > 0 &&
    items.every((i) => ["completed", "error"].includes(statusOf(i)));
  const canGenerate = allResolved && completed.length > 0;
  const generating = workbench?.guide_status === "generating";
  const guide = workbench?.design_guide ?? null;
  // A failure recorded on the row itself — either this session's run before a
  // reload, or a run the server abandoned (see lib/workbench/stale). Without
  // surfacing it the panel would sit on "Ready to generate" with nothing
  // driving it, since the auto-generate effect deliberately won't retry.
  const failedEarlier = !guide && workbench?.guide_status === "error";

  // Scan any source that hasn't been analyzed yet (once each).
  useEffect(() => {
    if (!workbench) return;
    for (const item of workbench.items) {
      if (statusOf(item) === "pending" && !autoScanned.current.has(item.id)) {
        autoScanned.current.add(item.id);
        scanItem(item);
      }
    }
  }, [workbench, scanItem]);

  // The user already asked for a guide by pressing Generate — run it as soon
  // as the sources are ready, exactly once.
  useEffect(() => {
    if (
      !autoGenerated.current &&
      workbench &&
      canGenerate &&
      !generating &&
      !guide &&
      workbench.guide_status !== "error"
    ) {
      autoGenerated.current = true;
      runGenerate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [workbench, canGenerate, generating, guide]);

  const runGenerate = async () => {
    setGenError(null);
    setOverLimit(false);
    setPartial("");
    try {
      await generate(setPartial);
    } catch (e) {
      const err = e as Error & { status?: number };
      setGenError(err.message || "Failed to generate guide");
      if (err.status === 402) setOverLimit(true);
    } finally {
      // The saved guide now comes from the workbench itself.
      setPartial("");
    }
  };

  const handleCopy = async () => {
    if (!guide) return;
    await navigator.clipboard.writeText(guide);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const goUpgrade = async () => {
    try {
      const res = await fetch("/api/billing/checkout", { method: "POST" });
      const data = await res.json();
      if (data.url) window.location.href = data.url;
    } catch {
      /* the error stays visible in the panel */
    }
  };

  return (
    <aside className="slide-in-right fixed inset-y-0 right-0 z-40 flex w-[min(400px,100vw)] flex-col border-l border-[var(--border)] bg-[var(--background)] shadow-2xl lg:static lg:z-auto lg:shadow-none">
      {/* Header */}
      <div className="border-b border-[var(--border)] px-5 pb-4 pt-5">
        <div className="flex items-center justify-between">
          <p className="font-mono text-[10px] uppercase tracking-[0.18em] text-[var(--text-muted)]">
            Mix
          </p>
          <button
            onClick={onClose}
            title="Close panel"
            className="rounded-md p-1 text-[var(--text-muted)] transition-colors hover:bg-[var(--border-light)] hover:text-[var(--foreground)]"
          >
            <X className="h-4 w-4" />
          </button>
        </div>
        {workbench && (
          <input
            key={workbench.id}
            defaultValue={workbench.name}
            onBlur={(e) => {
              const v = e.currentTarget.value.trim();
              if (v && v !== workbench.name) patchWorkbench({ name: v });
            }}
            title="Rename mix"
            className="mt-1 w-full truncate border-none bg-transparent font-[family-name:var(--font-display)] text-lg font-semibold text-[var(--foreground)] focus:outline-none focus:ring-0"
          />
        )}

        {/* Sources with scan status */}
        {items.length > 0 && (
          <div className="mt-2.5 flex flex-wrap gap-1.5">
            {items.map((item) => {
              const s = statusOf(item);
              return (
                <button
                  key={item.id}
                  onClick={() => s === "error" && scanItem(item)}
                  title={s === "error" ? "Scan failed — retry" : item.bookmark?.title}
                  className={cn(
                    "inline-flex max-w-[150px] items-center gap-1.5 rounded-full border px-2.5 py-1 text-[11.5px]",
                    s === "error"
                      ? "border-red-200 bg-red-50 text-red-600"
                      : "border-[var(--border)] bg-[var(--surface)] text-[var(--text-secondary)]"
                  )}
                >
                  {s === "completed" ? (
                    <Check className="h-3 w-3 shrink-0 text-[var(--accent)]" />
                  ) : s === "error" ? (
                    <RefreshCw className="h-3 w-3 shrink-0" />
                  ) : (
                    <Loader2 className="h-3 w-3 shrink-0 animate-spin" />
                  )}
                  <span className="truncate">
                    {item.bookmark?.domain || item.bookmark?.title || "source"}
                  </span>
                </button>
              );
            })}
          </div>
        )}

        {/* Your notes — the designer's own prompt; edit here, then
            regenerate to bake it into the guide. */}
        {workbench && (
          <div className="mt-3">
            <button
              onClick={() => setNotesOpen((v) => !v)}
              className="flex items-center gap-1 font-mono text-[10px] uppercase tracking-[0.16em] text-[var(--text-muted)] transition-colors hover:text-[var(--foreground)]"
            >
              Your notes
              {workbench.own_additions?.trim() && !notesOpen && (
                <span className="h-1 w-1 rounded-full bg-[var(--brand)]" />
              )}
              <ChevronDown
                className={cn(
                  "h-3 w-3 transition-transform",
                  notesOpen && "rotate-180"
                )}
              />
            </button>
            {notesOpen && (
              <textarea
                key={workbench.id}
                defaultValue={workbench.own_additions ?? ""}
                onBlur={(e) => {
                  const v = e.currentTarget.value;
                  if (v !== (workbench.own_additions ?? ""))
                    patchWorkbench({ own_additions: v });
                }}
                placeholder="Overall direction — what you're building, who it's for, the mood, any brand rules."
                rows={3}
                className="mt-2 w-full resize-none rounded-lg border border-[var(--border)] bg-[var(--surface)] px-3 py-2 text-xs text-[var(--foreground)] placeholder:text-[var(--text-muted)] focus:outline-none focus:ring-2 focus:ring-[var(--accent)]"
              />
            )}
          </div>
        )}
      </div>

      {/* Body */}
      <div className="flex min-h-0 flex-1 flex-col">
        {loading ? (
          <PanelStatus
            icon={<Loader2 className="h-5 w-5 animate-spin" />}
            line="Opening your mix…"
          />
        ) : !workbench ? (
          <PanelStatus
            icon={<AlertCircle className="h-5 w-5" />}
            line="This mix couldn't be loaded."
          />
        ) : guide ? (
          <>
            <div className="min-h-0 flex-1 overflow-y-auto px-5 py-4">
              <pre className="whitespace-pre-wrap font-sans text-[13px] leading-relaxed text-[var(--foreground)]">
                {guide}
              </pre>
            </div>
            <div className="border-t border-[var(--border)] px-5 py-3.5">
              {genError && (
                <p className="mb-2 text-xs text-red-500">{genError}</p>
              )}
              <div className="flex items-center gap-2">
                <Button size="sm" onClick={handleCopy} className="flex-1">
                  {copied ? (
                    <Check className="h-3.5 w-3.5" />
                  ) : (
                    <Copy className="h-3.5 w-3.5" />
                  )}
                  {copied ? "Copied" : "Copy for your agent"}
                </Button>
                <Button
                  size="sm"
                  variant="secondary"
                  onClick={runGenerate}
                  loading={generating}
                  disabled={!canGenerate || generating}
                  title="Regenerate guide"
                >
                  <RefreshCw className="h-3.5 w-3.5" />
                </Button>
                <Link
                  href={`/mix/${workbenchId}`}
                  className="inline-flex h-8 items-center gap-1 rounded-[var(--radius-button)] border border-[var(--border)] bg-[var(--surface)] px-3 text-sm font-medium text-[var(--foreground)] transition-colors hover:border-[var(--text-muted)]"
                  title="Open the full mix"
                >
                  Open
                  <ArrowUpRight className="h-3.5 w-3.5" />
                </Link>
              </div>
            </div>
          </>
        ) : generating ? (
          partial ? (
            <StreamingGuide text={partial} />
          ) : (
            <PanelStatus
              icon={<Sparkles className="h-5 w-5 text-[var(--accent)]" />}
              line="Writing your guide…"
              sub="Fusing what you tagged from each source. This can take a minute."
              skeleton
            />
          )
        ) : !allResolved ? (
          <PanelStatus
            icon={<Loader2 className="h-5 w-5 animate-spin" />}
            line={`Reading your sources — ${completed.length} of ${items.length} done`}
            sub="Each site gets a screenshot plus its fonts and colors."
            skeleton
          />
        ) : genError || failedEarlier ? (
          <div className="flex flex-1 flex-col items-center justify-center gap-3 px-8 text-center">
            <AlertCircle className="h-6 w-6 text-red-500" />
            <p className="text-sm text-[var(--text-secondary)]">
              {genError ?? "That generation didn't finish."}
            </p>
            {overLimit ? (
              <Button size="sm" onClick={goUpgrade}>
                <Zap className="h-3.5 w-3.5" />
                Upgrade to Pro
              </Button>
            ) : (
              <Button size="sm" variant="secondary" onClick={runGenerate}>
                Try again
              </Button>
            )}
          </div>
        ) : completed.length === 0 ? (
          <div className="flex flex-1 flex-col items-center justify-center gap-3 px-8 text-center">
            <AlertCircle className="h-6 w-6 text-[var(--text-muted)]" />
            <p className="text-sm text-[var(--text-secondary)]">
              None of the sources could be scanned. Tap a source above to
              retry.
            </p>
          </div>
        ) : (
          <PanelStatus
            icon={<Sparkles className="h-5 w-5 text-[var(--accent)]" />}
            line="Ready to generate"
            sub="Starting your guide…"
            skeleton
          />
        )}
      </div>
    </aside>
  );
}

/* The guide arriving live. Progress is read back out of the text itself —
   each "## " heading the model writes is one section done — so a change to the
   prompt's section list degrades to a still-truthful label instead of a wrong
   one. */
function StreamingGuide({ text }: { text: string }) {
  const scrollRef = useRef<HTMLDivElement>(null);
  const total = GUIDE_SECTIONS.length;

  const headings = text.match(/^##\s+(.+)$/gm) ?? [];
  const done = Math.min(headings.length, total);
  const label =
    headings.length > 0
      ? headings[headings.length - 1].replace(/^##\s+/, "").trim()
      : text.match(/^#\s+(.+)$/m)?.[1].trim() || "Getting started";

  // Follow the text down, but don't yank someone who scrolled back to read.
  useEffect(() => {
    const el = scrollRef.current;
    if (!el) return;
    if (el.scrollHeight - el.scrollTop - el.clientHeight < 40) {
      el.scrollTop = el.scrollHeight;
    }
  }, [text]);

  return (
    <>
      <div className="border-b border-[var(--border)] px-5 py-3.5">
        <div className="flex items-center gap-2">
          <Sparkles className="h-4 w-4 shrink-0 text-[var(--accent)]" />
          <p className="text-sm font-medium text-[var(--foreground)]">
            Writing your guide…
          </p>
        </div>
        <p className="mt-1 truncate pl-6 text-xs text-[var(--text-secondary)]">
          {label}
        </p>
        <div className="mt-2 flex items-center gap-2 pl-6">
          <div className="flex gap-1">
            {Array.from({ length: total }, (_, i) => (
              <span
                key={i}
                className={cn(
                  "h-1.5 w-1.5 rounded-full transition-colors",
                  i < done ? "bg-[var(--accent)]" : "bg-[var(--border)]"
                )}
              />
            ))}
          </div>
          <span className="font-mono text-[10px] text-[var(--text-muted)]">
            {done} of {total}
          </span>
        </div>
      </div>
      <div ref={scrollRef} className="min-h-0 flex-1 overflow-y-auto px-5 py-4">
        <pre className="whitespace-pre-wrap font-sans text-[13px] leading-relaxed text-[var(--foreground)]">
          {text}
          <span className="stream-caret" />
        </pre>
      </div>
    </>
  );
}

function PanelStatus({
  icon,
  line,
  sub,
  skeleton = false,
}: {
  icon: React.ReactNode;
  line: string;
  sub?: string;
  skeleton?: boolean;
}) {
  return (
    <div className="flex flex-1 flex-col px-5 py-6">
      <div className="flex flex-col items-center gap-2.5 pb-6 pt-10 text-center">
        <span className="text-[var(--text-secondary)]">{icon}</span>
        <p className="text-sm font-medium text-[var(--foreground)]">{line}</p>
        {sub && (
          <p className="max-w-[260px] text-xs leading-relaxed text-[var(--text-muted)]">
            {sub}
          </p>
        )}
      </div>
      {skeleton && (
        <div className="space-y-2.5 rounded-[var(--radius-card)] border border-[var(--border)] bg-[var(--surface)] p-4">
          <div className="h-3 w-2/5 animate-pulse rounded-full bg-[var(--border-light)]" />
          <div className="h-3 w-full animate-pulse rounded-full bg-[var(--border-light)]" />
          <div className="h-3 w-4/5 animate-pulse rounded-full bg-[var(--border-light)]" />
          <div className="h-3 w-3/5 animate-pulse rounded-full bg-[var(--border-light)]" />
          <div className="mt-3 flex gap-1.5">
            {["#FBFAF7", "#221C15", "#8D6F4C", "#C25E6A"].map((c) => (
              <span
                key={c}
                className="h-6 flex-1 animate-pulse rounded-md border border-[var(--border)]"
                style={{ background: c, opacity: 0.5 }}
              />
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
